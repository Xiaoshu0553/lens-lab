def review_inventory() -> dict:
    forms = []
    for band in AGE_BANDS:
        version, items = form_for(band)
        forms.append({"age_band": band, "age_label": AGE_BANDS[band]["label"],
                      "version": version, "items": deepcopy(items)})
    return {"status": REVIEW_STATUS, "legacy_candidate_count": len(LEGACY_REVIEW),
            "legacy_items": deepcopy(LEGACY_REVIEW), "forms": forms,
            "form_item_count": sum(len(form["items"]) for form in forms),
            "unique_current_material_count": len({(item["question"], tuple(item["options"]))
                for form in forms for item in form["items"]})}
