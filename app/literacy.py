def _make_item(key: str, domain: str, question: str, options: tuple[str, str, str],
               correct: int, difficulty: str, *, rationale: str = "",
               skill: str = "", expected_knowledge: str = "", review_note: str = "") -> dict:
    """Freeze option order within this version without a visible repeating key."""
    order = sorted(range(len(options)), key=lambda index: hashlib.sha256(
        f"{VERSION}:{key}:option-{index}".encode()).digest())
    if key in ITEM_BLUEPRINT:
        ranked_keys = sorted(ITEM_BLUEPRINT, key=lambda item_id: hashlib.sha256(
            f"{VERSION}:{item_id}:key-slot".encode()).digest())
        key_position = ranked_keys.index(key) % 3
        order.remove(correct)
        order.insert(key_position, correct)
    return {"id": key, "domain": domain, "question": question,
            "options": [*(options[index] for index in order), "我暂时不会选"],
            "correct": order.index(correct), "draft_difficulty": "unrated",
            "difficulty_basis": "未经过实测；可读性修订后不预设易中难比例，也不以术语或句长制造难度",
            "rationale": rationale, "skill": skill,
            "expected_knowledge": expected_knowledge,
            "review_note": review_note}


def make_reviewed_item(entry: tuple, *, age_band: str = "shared") -> dict:
    key, domain, question, options, correct, rationale = entry
    skill, knowledge, difficulty = ITEM_BLUEPRINT[key]
    item = _make_item(key, domain, question, options, correct, difficulty,
                      rationale=rationale, skill=skill, expected_knowledge=knowledge,
                      review_note=("材料内作答；两个实质干扰项需由预测试的选项选择率及题总相关复核。"
                                   "按短句或分行复核；实际是否读懂仍需受试者复述题意核验；年龄不证明常识一致或跨卷等值。"))
    item.update(anchor=key in ANCHOR_IDS, age_band=age_band)
    return item


_BANK = ANCHOR_BANK + DEFAULT_CONTEXT_BANK
ITEMS = sorted([make_reviewed_item(entry) for entry in _BANK], key=lambda item: int(item["id"][1:]))


def public_items() -> list[dict]:
    return [{"id": item["id"], "domain": item["domain"], "question": item["question"],
             "options": list(item["options"])} for item in ITEMS]


def score_answers(answers: dict[str, int], band_width: int = 10) -> tuple[int, float, str]:
    if not isinstance(answers, dict) or set(answers) != {item["id"] for item in ITEMS}:
        raise ValueError("请完成全部信息判断题")
    if any(type(answers[item["id"]]) is not int or not 0 <= answers[item["id"]] < len(item["options"]) for item in ITEMS):
        raise ValueError("信息判断题的选项无效")
    if type(band_width) is not int or band_width < 1 or 100 % band_width:
        raise ValueError("信息素养区间宽度必须能整除 100")
    raw = sum(answers[item["id"]] == item["correct"] for item in ITEMS)
    percent = round(raw * 100 / len(ITEMS), 2)
    start = min(100 - band_width, int(percent // band_width) * band_width)
    return raw, percent, f"{start:03d}-{start + band_width:03d}"


def band_label(key: str) -> str:
    start, end = (int(part) for part in key.split("-"))
    return f"{start}–{end}%" if end == 100 else f"{start}–<{end}%"
